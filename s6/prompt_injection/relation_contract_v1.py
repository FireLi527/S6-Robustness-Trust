"""Evidence-bearing multi-action extraction contract, independent of classifiers."""
from __future__ import annotations

KINDS = ("requested", "prohibited", "quoted", "plan", "simulation")
TARGET_STATES = ("explicit", "ambiguous", "unmapped", "unspecified")
MODES = ("execute", "plan_only", "simulate_only", "quote_only", "unknown")
TARGET_SCHEMA = {"type": "object", "additionalProperties": False, "properties": {
    "mention": {"type": ["string", "null"]}, "status": {"type": "string", "enum": list(TARGET_STATES)},
    "candidates": {"type": "array", "items": {"type": "string"}}}, "required": ["mention", "status", "candidates"]}
ACTION_SCHEMA = {"type": "object", "additionalProperties": False, "properties": {
    "operation": {"type": "string"}, "kind": {"type": "string", "enum": list(KINDS)},
    "targets": {"type": "array", "minItems": 1, "items": TARGET_SCHEMA}, "evidence": {"type": "string"}},
    "required": ["operation", "kind", "targets", "evidence"]}
SCHEMA = {"type": "object", "additionalProperties": False, "properties": {
    "mode": {"type": "string", "enum": list(MODES)},
    "actions": {"type": "array", "items": ACTION_SCHEMA},
    "constraints": {"type": "array", "items": {"type": "string"}},
    "missing_context": {"type": "array", "items": {"type": "string"}}},
    "required": ["mode", "actions", "constraints", "missing_context"]}


def source_span(source: str, text: str) -> dict:
    """Index exact Unicode text; offsets are derived, not generated by the model."""
    if not isinstance(text, str) or not text or text not in source:
        raise ValueError("Evidence is not a nonempty exact source substring")
    start = source.index(text)
    return {"text": text, "start": start, "end": start + len(text)}


def validate_target(target: dict, source: str, evidence: str) -> None:
    """Never silently resolve an ambiguous or missing target from permissions."""
    if not isinstance(target, dict) or set(target) != {"mention", "status", "candidates"}:
        raise ValueError("Invalid target fields")
    status, mention, candidates = target["status"], target["mention"], target["candidates"]
    if status not in TARGET_STATES or not isinstance(candidates, list):
        raise ValueError("Invalid target status or candidates")
    if mention is not None:
        source_span(evidence, mention)
    if (status == "unspecified") != (mention is None):
        raise ValueError("Only unspecified targets have null mentions")
    for candidate in candidates:
        source_span(source, candidate)
    if status == "explicit" and candidates != [mention]:
        raise ValueError("Explicit target must preserve its literal identity")
    if status == "ambiguous" and len(set(candidates)) < 2:
        raise ValueError("Ambiguous target requires multiple source candidates")
    if status in ("unmapped", "unspecified") and candidates:
        raise ValueError("Do not invent candidates for missing mappings")


def validate(value: dict, source: str) -> dict:
    """Validate form and grounding only, NOT semantic correctness or permission."""
    if not isinstance(value, dict) or set(value) != set(SCHEMA["required"]) or value["mode"] not in MODES:
        raise ValueError("Invalid extraction fields/mode")
    for field in ("actions", "constraints", "missing_context"):
        if not isinstance(value[field], list):
            raise ValueError("Expected list")
    for text in value["constraints"] + value["missing_context"]:
        source_span(source, text)
    evidence_spans = []
    for action in value["actions"]:
        if not isinstance(action, dict) or set(action) != set(ACTION_SCHEMA["required"]) or action["kind"] not in KINDS:
            raise ValueError("Invalid action fields/kind")
        evidence = action["evidence"]
        evidence_spans.append(source_span(source, evidence))
        source_span(evidence, action["operation"])
        if not isinstance(action["targets"], list) or not action["targets"]:
            raise ValueError("Action requires targets, including explicit unspecified state")
        for target in action["targets"]:
            validate_target(target, source, evidence)
    return {"action_evidence_spans": evidence_spans, "semantic_correctness_verified": False,
            "tool_authorization": "not_granted"}
